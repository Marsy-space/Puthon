"""Собственные исключения приложения.

Все исключения приложения наследуются от LabError, чтобы в main.py
их можно было перехватывать одним except LabError и показывать
пользователю понятное сообщение, не роняя программу.
"""


class LabError(Exception):
    """Базовое исключение приложения."""


class ValidationError(LabError):
    """Некорректные данные: неверный тип, диапазон, пустое обязательное поле."""


class CsvFormatError(LabError):
    """Ошибка формата CSV-файла (не хватает колонок, битая строка и т.п.)."""


class FileAccessError(LabError):
    """Ошибка доступа к файлу: файл не найден, нет прав на чтение/запись."""


class StudentNotFoundError(LabError):
    """Студент с указанным id не найден в списке."""


class DuplicateStudentError(LabError):
    """Студент с таким id уже существует в списке."""
